#!/usr/bin/env python3
"""Build the Android launcher icons from the Blender icon renders.

Inputs (rendered by art/blender/icon.py): art/icon/icon_{background,
foreground,monochrome,full}.png, each 1024x1024. They live outside
app/assets so the full-size renders aren't bundled into the app.
Outputs: app/android/app/src/main/res/mipmap-*/ic_launcher*.png and the
adaptive-icon XML (Android 8+, with a monochrome layer for Android 13 themed
icons). Needs ffmpeg.

    python3 art/android_icons.py
"""
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "art" / "icon"
RES = ROOT / "app" / "android" / "app" / "src" / "main" / "res"

# Adaptive icon layers are 108dp; legacy icons are 48dp.
DENSITIES = {"mdpi": 1.0, "hdpi": 1.5, "xhdpi": 2.0, "xxhdpi": 3.0, "xxxhdpi": 4.0}

ADAPTIVE_XML = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by art/android_icons.py -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@mipmap/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
    <monochrome android:drawable="@mipmap/ic_launcher_monochrome" />
</adaptive-icon>
"""


def scale(src: Path, dst: Path, size: int) -> None:
    dst.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        ["ffmpeg", "-loglevel", "error", "-y", "-i", str(src),
         "-vf", f"scale={size}:{size}:flags=lanczos", str(dst)],
        check=True,
    )


def main() -> None:
    for name, factor in DENSITIES.items():
        folder = RES / f"mipmap-{name}"
        layer = round(108 * factor)
        scale(SRC / "icon_background.png", folder / "ic_launcher_background.png", layer)
        scale(SRC / "icon_foreground.png", folder / "ic_launcher_foreground.png", layer)
        scale(SRC / "icon_monochrome.png", folder / "ic_launcher_monochrome.png", layer)
        scale(SRC / "icon_full.png", folder / "ic_launcher.png", round(48 * factor))
    anydpi = RES / "mipmap-anydpi-v26"
    anydpi.mkdir(parents=True, exist_ok=True)
    (anydpi / "ic_launcher.xml").write_text(ADAPTIVE_XML)
    print(f"launcher icons written under {RES.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
