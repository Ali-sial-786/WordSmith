#!/usr/bin/env node
/**
 * Builds the SQL that loads the multiplayer puzzle bank into D1's `puzzles`
 * table (pool 'mp'), which rooms draw from (docs/TECH.md §6).
 *
 * Reads data/mp_bank.json (shared/puzzle-format.md, with `size`) and writes
 * data/bank.sql: one `INSERT OR REPLACE` per puzzle, plus a DELETE for
 * multiplayer puzzles that are no longer in the bank. The output only
 * depends on the input file, so re-running it is safe and the file needn't
 * be committed (it's git-ignored).
 *
 *   node scripts/build-bank-sql.mjs [mp_bank.json] [out.sql]
 *   npm run db:bank           # just build data/bank.sql
 *   npm run db:seed:local     # build campaign + bank SQL, load both into the local D1
 *
 * vitest.config.ts imports loadBankRows() to load the same rows into the
 * test database.
 */

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const DEFAULT_BANK_PATH = resolve(here, "../data/mp_bank.json");
export const DEFAULT_OUT_PATH = resolve(here, "../data/bank.sql");

const ID = /^m-\d{5}$/;
const LETTERS = /^[A-Z]{4,8}$/;
const WORD = /^[A-Z]{3,8}$/;
const isInt = (v, min, max) => Number.isInteger(v) && v >= min && v <= max;

/**
 * The `puzzles` rows for a parsed mp_bank.json: `[{id, heat, size, letters, data}]`,
 * where `data` is the puzzle's JSON text. Throws if the bank breaks the
 * format's basic rules.
 */
export function bankRows(bank) {
  if (bank === null || typeof bank !== "object" || !Array.isArray(bank.puzzles)) {
    throw new Error("mp_bank.json: expected {puzzles: [...]}");
  }
  const seen = new Set();
  return bank.puzzles.map((puzzle, i) => {
    const fail = (why) => {
      throw new Error(`mp_bank.json puzzle ${i} (${JSON.stringify(puzzle?.id)}): ${why}`);
    };
    if (puzzle === null || typeof puzzle !== "object") fail("not an object");
    if (typeof puzzle.id !== "string" || !ID.test(puzzle.id)) fail("id must be m-NNNNN");
    if (seen.has(puzzle.id)) fail("duplicate id");
    seen.add(puzzle.id);
    if (typeof puzzle.letters !== "string" || !LETTERS.test(puzzle.letters)) fail("bad letters");
    if (!isInt(puzzle.heat, 1, 6)) fail("heat must be 1-6");
    if (!isInt(puzzle.size, 1, 4)) fail("size must be 1-4");
    if (!isInt(puzzle.cols, 1, 10) || !isInt(puzzle.rows, 1, 10)) fail("bad grid size");
    if (!Array.isArray(puzzle.words) || puzzle.words.length === 0) fail("no words");
    for (const w of puzzle.words) {
      if (typeof w?.w !== "string" || !WORD.test(w.w)) fail(`bad word ${JSON.stringify(w?.w)}`);
      if (!isInt(w.x, 0, 9) || !isInt(w.y, 0, 9) || (w.d !== "a" && w.d !== "d")) fail(`bad slot for ${w.w}`);
    }
    if (!Array.isArray(puzzle.bonus) || !puzzle.bonus.every((b) => typeof b === "string")) fail("bad bonus list");
    return { id: puzzle.id, heat: puzzle.heat, size: puzzle.size, letters: puzzle.letters, data: JSON.stringify(puzzle) };
  });
}

export function loadBankRows(path = DEFAULT_BANK_PATH) {
  let text;
  try {
    text = readFileSync(path, "utf8");
  } catch (err) {
    throw new Error(`Can't read the puzzle bank at ${path} (generate it with tools/puzzlegen): ${err.message}`);
  }
  return bankRows(JSON.parse(text));
}

const sqlString = (s) => `'${s.replaceAll("'", "''")}'`;

/**
 * The bank's ids as runs of consecutive numbers, `[[first, last], …]`. Ids
 * are `m-` and five digits, so they sort as strings the way they do as
 * numbers, and a run can be an SQL `BETWEEN`.
 */
function idRanges(rows) {
  const ns = rows.map((r) => Number(r.id.slice(2))).sort((a, b) => a - b);
  const ranges = [];
  for (const n of ns) {
    const last = ranges.at(-1);
    if (last !== undefined && n === last[1] + 1) last[1] = n;
    else ranges.push([n, n]);
  }
  const id = (n) => sqlString(`m-${String(n).padStart(5, "0")}`);
  return ranges.map(([a, b]) => [id(a), id(b)]);
}

/**
 * Each statement is one line and stays small (D1 refuses statements over
 * 100 KB): one per puzzle, and the DELETE names the kept ids as ranges
 * rather than one by one, so it doesn't grow with the bank.
 *
 * Every deploy runs this, so a puzzle that hasn't changed must cost no
 * write: D1's free plan allows 100,000 rows written a day, and rewriting
 * the whole bank (each row and its index entries) took about a sixth of it.
 * So each puzzle is an upsert that only updates when something differs.
 */
export function bankSql(rows) {
  const kept = idRanges(rows)
    .map(([a, b]) => (a === b ? `id = ${a}` : `id BETWEEN ${a} AND ${b}`))
    .join(" OR ");
  const lines = [
    "-- Generated by server/scripts/build-bank-sql.mjs from server/data/mp_bank.json.",
    "-- Do not edit; re-run the script instead.",
    rows.length === 0 ? "DELETE FROM puzzles WHERE pool = 'mp';" : `DELETE FROM puzzles WHERE pool = 'mp' AND NOT (${kept});`,
  ];
  for (const row of rows) {
    lines.push(
      `INSERT INTO puzzles (id, pool, heat, size, letters, data) VALUES (${sqlString(row.id)}, 'mp', ${row.heat}, ${row.size}, ${sqlString(row.letters)}, ${sqlString(row.data)})` +
        " ON CONFLICT (id) DO UPDATE SET pool = excluded.pool, heat = excluded.heat, size = excluded.size, letters = excluded.letters, data = excluded.data" +
        " WHERE puzzles.pool IS NOT excluded.pool OR puzzles.heat IS NOT excluded.heat OR puzzles.size IS NOT excluded.size" +
        " OR puzzles.letters IS NOT excluded.letters OR puzzles.data IS NOT excluded.data;",
    );
  }
  return lines.join("\n") + "\n";
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const input = resolve(process.argv[2] ?? DEFAULT_BANK_PATH);
  const output = resolve(process.argv[3] ?? DEFAULT_OUT_PATH);
  const rows = loadBankRows(input);
  mkdirSync(dirname(output), { recursive: true });
  writeFileSync(output, bankSql(rows));
  console.log(`Wrote ${rows.length} multiplayer puzzles to ${output}`);
}
