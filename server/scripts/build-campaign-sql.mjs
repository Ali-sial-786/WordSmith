#!/usr/bin/env node
/**
 * Builds the SQL that loads the campaign into D1's `campaign` table, so the
 * server can check solo syncs (docs/TECH.md §8).
 *
 * Reads ../app/assets/campaign/campaign.json (shared/puzzle-format.md) and
 * writes data/campaign.sql: one `INSERT OR REPLACE` per stage, plus a
 * DELETE for stages that no longer exist. The output only depends on the
 * input files, so re-running it is safe and the file needn't be committed
 * (it's git-ignored).
 *
 * It also loads the earlier campaign editions ({@link EARLIER_EDITIONS}:
 * the campaigns of earlier app versions, kept in data/) into
 * `campaign_previous`, one row per edition and stage, so results played on
 * them still count (apps with an old campaign built in, results queued
 * before an update; src/rules/campaign.ts `editionFor`). An edition whose
 * file is missing is left out, and its rows are deleted.
 *
 *   node scripts/build-campaign-sql.mjs [campaign.json] [out.sql]
 *   npm run db:seed:local     # build, then load into the local D1
 *
 * vitest.config.ts imports campaignRows() to load the same rows into the
 * test database.
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const DEFAULT_CAMPAIGN_PATH = resolve(here, "../../app/assets/campaign/campaign.json");
export const DEFAULT_OUT_PATH = resolve(here, "../data/campaign.sql");

/**
 * The earlier campaign editions, oldest first: `edition` numbers them (the
 * `campaign_previous.edition` column), `app` is the app version that has
 * it built in. When the campaign is regenerated, save the outgoing
 * campaign.json in data/ and add it here with the next number. Drop an
 * edition only when no supported app version has it.
 */
export const EARLIER_EDITIONS = [
  { edition: 1, app: "0.8.0", path: resolve(here, "../data/campaign_previous.json") },
  { edition: 2, app: "0.9.0", path: resolve(here, "../data/campaign_previous_0.9.0.json") },
];

/** `c-` + stage padded to 4 digits (shared/puzzle-format.md). */
function puzzleId(stage) {
  return `c-${String(stage).padStart(4, "0")}`;
}

/**
 * The campaign table rows for a parsed campaign.json:
 * `[{stage, puzzleId, data}]`, where `data` is the puzzle's JSON text.
 * Throws if the file breaks the format's basic rules.
 */
export function campaignRows(campaign) {
  if (campaign === null || typeof campaign !== "object" || !Array.isArray(campaign.puzzles)) {
    throw new Error("campaign.json: expected {puzzles: [...]}");
  }
  return campaign.puzzles.map((puzzle, i) => {
    const stage = i + 1;
    const fail = (why) => {
      throw new Error(`campaign.json stage ${stage}: ${why}`);
    };
    if (puzzle === null || typeof puzzle !== "object") fail("not an object");
    if (puzzle.id !== puzzleId(stage)) fail(`id is ${JSON.stringify(puzzle.id)}, expected ${puzzleId(stage)}`);
    if (!Array.isArray(puzzle.words) || puzzle.words.length === 0) fail("no words");
    for (const w of puzzle.words) {
      if (typeof w?.w !== "string" || !/^[A-Z]{3,}$/.test(w.w)) fail(`bad word ${JSON.stringify(w?.w)}`);
      if (!Number.isInteger(w.x) || !Number.isInteger(w.y) || (w.d !== "a" && w.d !== "d")) fail(`bad slot for ${w.w}`);
    }
    if (!Array.isArray(puzzle.bonus) || !puzzle.bonus.every((b) => typeof b === "string")) fail("bad bonus list");
    return { stage, puzzleId: puzzle.id, data: JSON.stringify(puzzle) };
  });
}

export function loadCampaignRows(path = DEFAULT_CAMPAIGN_PATH) {
  let text;
  try {
    text = readFileSync(path, "utf8");
  } catch (err) {
    throw new Error(`Can't read the campaign at ${path} (generate it with tools/puzzlegen): ${err.message}`);
  }
  return campaignRows(JSON.parse(text));
}

/**
 * The earlier editions' rows, `[{edition, stage, puzzleId, data}]`, oldest
 * edition first; an edition whose file doesn't exist has none.
 */
export function loadEarlierCampaignRows(editions = EARLIER_EDITIONS) {
  return editions.flatMap(({ edition, path }) => {
    if (!existsSync(path)) return [];
    return campaignRows(JSON.parse(readFileSync(path, "utf8"))).map((row) => ({ edition, ...row }));
  });
}

const sqlString = (s) => `'${s.replaceAll("'", "''")}'`;

/**
 * Every deploy runs this, so a stage that hasn't changed must cost no write
 * (D1's free plan allows 100,000 rows written a day): each stage is an
 * upsert that only updates when something differs.
 */
export function campaignSql(rows, earlier = []) {
  const lines = [
    "-- Generated by server/scripts/build-campaign-sql.mjs from app/assets/campaign/campaign.json",
    "-- and the earlier editions in data/. Do not edit; re-run the script instead.",
  ];
  const upsert = (table, key, row, cols, values) =>
    `INSERT INTO ${table} (${cols}, puzzle_id, data) VALUES (${values}, ${sqlString(row.puzzleId)}, ${sqlString(row.data)})` +
    ` ON CONFLICT (${key}) DO UPDATE SET puzzle_id = excluded.puzzle_id, data = excluded.data` +
    ` WHERE ${table}.puzzle_id IS NOT excluded.puzzle_id OR ${table}.data IS NOT excluded.data;`;
  lines.push(`DELETE FROM campaign WHERE stage > ${rows.length};`);
  for (const row of rows) lines.push(upsert("campaign", "stage", row, "stage", `${row.stage}`));

  const stages = new Map();
  for (const row of earlier) stages.set(row.edition, Math.max(stages.get(row.edition) ?? 0, row.stage));
  const editions = [...stages.keys()].sort((a, b) => a - b);
  lines.push(editions.length === 0 ? "DELETE FROM campaign_previous;" : `DELETE FROM campaign_previous WHERE edition NOT IN (${editions.join(", ")});`);
  for (const e of editions) lines.push(`DELETE FROM campaign_previous WHERE edition = ${e} AND stage > ${stages.get(e)};`);
  for (const row of earlier) lines.push(upsert("campaign_previous", "edition, stage", row, "edition, stage", `${row.edition}, ${row.stage}`));
  return lines.join("\n") + "\n";
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const input = resolve(process.argv[2] ?? DEFAULT_CAMPAIGN_PATH);
  const output = resolve(process.argv[3] ?? DEFAULT_OUT_PATH);
  const rows = loadCampaignRows(input);
  const earlier = loadEarlierCampaignRows();
  mkdirSync(dirname(output), { recursive: true });
  writeFileSync(output, campaignSql(rows, earlier));
  const editions = new Set(earlier.map((r) => r.edition)).size;
  console.log(`Wrote ${rows.length} campaign stages and ${earlier.length} stages of ${editions} earlier editions to ${output}`);
}
