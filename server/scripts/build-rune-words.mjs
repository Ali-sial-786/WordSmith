#!/usr/bin/env node
/**
 * Writes src/rules/rune-words.gen.ts: the words Rune Rush takes
 * (shared/rune-rush.md). They're the everyday part of the puzzles' accepted
 * words (tools/puzzlegen/data/accepted.txt: 3-8 letters, no names or blocked
 * words), so a word only counts if players would call it a real word:
 *
 * - SCOWL levels 10 and 20 (the commonest words): all of them.
 * - Levels 35 and 40: words wordfreq knows at all, and the -ier/-iest forms
 *   of their -y words (`yuckiest`), which wordfreq often doesn't.
 * - Levels 50 and 55: words of Zipf frequency 2.3 or more, and words wordfreq
 *   knows that are a plural or verb form of a common level <= 40 word.
 * - Rarer (levels 60, 70, and words only ENABLE has): none, except
 *   tools/puzzlegen/data/rune_allow.txt (newer words like `meetup`) and their
 *   accepted inflections.
 * - Never tools/puzzlegen/data/rune_block.txt (`och`, `nowt`, `tireder`).
 *
 * Levels come from data/scowl_levels.tsv and frequencies from data/freq.tsv
 * (wordfreq, CC BY-SA 4.0; sources and credits in data/LICENSES.md).
 *
 *   node scripts/build-rune-words.mjs
 *
 * Re-run after any of those files change. The words go in as one sorted,
 * newline-separated string, which rules/rune.ts splits the first time a
 * board is made.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const data = join(here, "../../tools/puzzlegen/data");
const target = join(here, "../src/rules/rune-words.gen.ts");

const lines = (file) =>
  readFileSync(join(data, file), "utf8")
    .split("\n")
    .map((l) => l.trim())
    .filter((l) => l !== "");
/** The words in a hand-written list: several a line, `#` comments. */
const list = (file) =>
  new Set(
    lines(file)
      .map((l) => l.replace(/#.*/, ""))
      .flatMap((l) => l.split(/\s+/))
      .filter((w) => w !== ""),
  );
const table = (file) => new Map(lines(file).map((l) => l.split("\t")).map(([w, v]) => [w, Number(v)]));

const accepted = new Set(lines("accepted.txt"));
const level = table("scowl_levels.tsv");
const zipf = table("freq.tsv");
const allow = list("rune_allow.txt");
const block = list("rune_block.txt");
for (const w of [...accepted, ...allow, ...block]) {
  if (!/^[a-z]{3,8}$/.test(w)) throw new Error(`unexpected word: ${JSON.stringify(w)}`);
}

const lvl = (w) => level.get(w) ?? 99;
const freq = (w) => zipf.get(w) ?? 0;

/** Accepted words [w] could be a plural, verb or comparative form of. */
const SUFFIXES = [
  ["ies", "y"], ["iest", "y"], ["ier", "y"], ["ied", "y"], ["ily", "y"],
  ["es", ""], ["s", ""], ["ed", ""], ["ed", "e"], ["d", ""], ["ing", ""], ["ing", "e"],
  ["er", ""], ["er", "e"], ["est", ""], ["est", "e"], ["ly", ""], ["ness", ""],
];
const UNDOUBLE = new Set(["ed", "ing", "er", "est"]);
function bases(w) {
  const out = [];
  for (const [suffix, add] of SUFFIXES) {
    if (!w.endsWith(suffix) || w.length - suffix.length < 3) continue;
    const b = w.slice(0, -suffix.length) + add;
    out.push(b);
    // stopped, stopping: stop
    if (b.length >= 4 && b.at(-1) === b.at(-2) && UNDOUBLE.has(suffix)) out.push(b.slice(0, -1));
  }
  return out.filter((b) => accepted.has(b));
}

/** gooier, gooiest: from a -y word of level <= 40. */
const yForm = (w) =>
  ["iest", "ier"].some((s) => w.endsWith(s) && lvl(w.slice(0, -s.length) + "y") <= 40);

function everyday(w) {
  const l = lvl(w);
  const z = freq(w);
  if (l <= 20) return true;
  if (l <= 40) return z >= 1 || yForm(w);
  if (l <= 55) return z >= 2.3 || (z >= 1 && bases(w).some((b) => lvl(b) <= 40 && freq(b) >= 3));
  return false;
}

const words = new Set([...accepted].filter((w) => everyday(w) || bases(w).some((b) => allow.has(b))));
for (const w of allow) words.add(w);
for (const w of block) words.delete(w);
const sorted = [...words].sort();

writeFileSync(
  target,
  [
    "// Generated by scripts/build-rune-words.mjs from tools/puzzlegen/data (accepted.txt,",
    "// scowl_levels.tsv, freq.tsv, rune_allow.txt, rune_block.txt). Do not edit.",
    `// ${sorted.length} everyday words, sorted, lowercase a-z, 3-8 letters.`,
    `export const RUNE_WORDS = ${JSON.stringify(sorted.join("\n"))};`,
    "",
  ].join("\n"),
);
console.log(`wrote ${target}: ${sorted.length} words`);
