#!/usr/bin/env node
/**
 * Writes src/rules/rune-words.gen.ts: every accepted word (the same list as
 * the puzzles' bonus words, tools/puzzlegen/data/accepted.txt: 3-8 letters,
 * no names or blocked words), for refereeing Rune Grid (shared/rune-grid.md).
 *
 *   node scripts/build-rune-words.mjs
 *
 * Re-run after the word list changes. The words go in as one sorted,
 * newline-separated string, which rules/rune.ts splits the first time a
 * board is made.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = join(here, "../../tools/puzzlegen/data/accepted.txt");
const target = join(here, "../src/rules/rune-words.gen.ts");

const words = readFileSync(source, "utf8")
  .split("\n")
  .map((w) => w.trim())
  .filter((w) => w !== "");
for (const w of words) if (!/^[a-z]{3,8}$/.test(w)) throw new Error(`unexpected word: ${JSON.stringify(w)}`);
const sorted = [...new Set(words)].sort();

writeFileSync(
  target,
  [
    "// Generated by scripts/build-rune-words.mjs from tools/puzzlegen/data/accepted.txt. Do not edit.",
    `// ${sorted.length} words, sorted, lowercase a-z, 3-8 letters.`,
    `export const RUNE_WORDS = ${JSON.stringify(sorted.join("\n"))};`,
    "",
  ].join("\n"),
);
console.log(`wrote ${target}: ${sorted.length} words`);
